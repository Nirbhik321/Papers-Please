"""
Run every experiment and regenerate every figure:

    .venv/Scripts/python -m eval.run_all                 # everything
    .venv/Scripts/python -m eval.run_all --only grouping # one stage
    .venv/Scripts/python -m eval.run_all --reextract     # re-run extraction after code changes

Inputs (gitignored): data/raw/*.pdf, data/eval/ground_truth/. Outputs (committed):
eval/results/results.json, eval/results/RESULTS.md, eval/results/figures/*.pdf|png.
"""

import argparse
import json
import shutil
import statistics

from eval import experiments, extract_system, figures
from eval.common import FIGURES, RESULTS, ROOT, load_gt_groups, load_gt_papers, load_system, write_json

STAGES = ["extraction", "grouping", "backtest", "perf"]


def summary_md(res: dict) -> str:
    out = ["# Evaluation results", "", "Generated by `python -m eval.run_all`. Every number in the paper comes from here.", ""]
    if "extraction" in res:
        out += ["## Extraction (vs hand transcriptions)", "",
                "| PDFs | Papers | Gold q | Extracted | P | R | F1 | Module | Q label | Marks | Text sim |",
                "|---|---|---|---|---|---|---|---|---|---|---|"]
        for k, s in res["extraction"]["summary"].items():
            out.append(f"| {k} | {s['papers']} | {s['gold']} | {s['extracted']} | {s['precision']:.3f} | {s['recall']:.3f} | "
                       f"{s['f1']:.3f} | {s['module_acc']:.3f} | {s['label_acc']:.3f} | {s['marks_acc']:.3f} | {s['text_sim']:.3f} |")
        out.append("")
    if "grouping" in res:
        g = res["grouping"]
        out += [f"## Grouping ({g['items']} questions, {g['gold_groups']} gold groups)", "",
                "| Model | Algorithm | Text | Size MB | best τ | P | R | F1 @best | F1 @0.70 | LOSO F1 | B³ F1 |",
                "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in sorted(g["runs"], key=lambda r: -r["loso"]["f1"]):
            b = r["best"]
            out.append(f"| {r['model']} | {r['algorithm']} | {r['variant']} | {r['size_mb']} | {r['best_threshold']:.3f} | "
                       f"{b['precision']:.3f} | {b['recall']:.3f} | {b['f1']:.3f} | {r['at_production_threshold']['f1']:.3f} | "
                       f"{r['loso']['f1']:.3f} | {r['best_bcubed_f1']:.3f} |")
        out.append("")
    if "backtest" in res:
        b = res["backtest"]
        out += ["## Backtest: marks secured in the next exam (/100) studying top-k topics per module", ""]
        hdr = "| Exam | Trained on | Repeat share | Ceiling | " + " | ".join(f"k={k}" for k in b["ks"]) + " |"
        out += [hdr, "|" + "---|" * (4 + len(b["ks"]))]
        for c in b["cases"]:
            for m, curve in c["curves"].items():
                out.append(f"| {c['subject']} {c['test_session']} [{m}] | {len(c['train'])} | {c['repeat_share_of_marks']:.2f} | "
                           f"{c['ceiling_all_seen']:.0f} | " + " | ".join(f"{v:.1f}" for v in curve) + " |")
        out.append("")
        if b.get("duplicates_dropped"):
            out.append(f"Duplicate scans dropped: {b['duplicates_dropped']}")
            out.append("")
    if "perf" in res:
        p = res["perf"]
        out += ["## Performance", ""]
        for kind in ("native", "scanned"):
            pp = [(e["extract_s"] + e["parse_s"]) / e["pages"] for e in p["extraction"] if e["pdf_type"] == kind]
            if pp:
                out.append(f"- {kind}: {statistics.mean(pp):.2f} s/page (n={len(pp)} papers)")
        for k in ("embedding_onnx", "embedding_torch"):
            if k in p:
                out.append(f"- {k}: {json.dumps({x: (round(v, 2) if isinstance(v, float) else v) for x, v in p[k].items()})}")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", choices=STAGES, nargs="*")
    ap.add_argument("--reextract", action="store_true")
    ap.add_argument("--models", nargs="*", help="limit the grouping comparison to these models")
    args = ap.parse_args()
    stages = args.only or STAGES

    results_path = RESULTS / "results.json"
    res = json.loads(results_path.read_text("utf-8")) if results_path.exists() else {}

    extract_system.run(force=args.reextract)
    gt, groups, system = load_gt_papers(), load_gt_groups(), load_system()

    if "extraction" in stages:
        print("Extraction…")
        res["extraction"] = experiments.extraction_eval(gt, system)
        figures.extraction(res["extraction"])
    if "grouping" in stages and groups:
        print("Grouping…")
        res["grouping"] = experiments.grouping_eval(gt, groups, args.models)
        runs = res["grouping"]["runs"]
        prod = next(r for r in runs if r["model"] == experiments.embedders.PRODUCTION
                    and r["algorithm"] == "greedy" and r["variant"] == "raw")
        best = max(runs, key=lambda r: r["loso"]["f1"])
        figures.threshold_sweep(res["grouping"], prod, best)
        res["grouping_hybrid"] = experiments.hybrid_eval(gt, groups, [experiments.embedders.DEPLOYED,
                                                                      experiments.embedders.PRODUCTION])
        figures.models(res["grouping"])
    if "backtest" in stages and groups:
        print("Backtest…")
        res["backtest"] = experiments.backtest(gt, groups, system)
        figures.backtest(res["backtest"])
        figures.backtest_cases(res["backtest"])
    if "perf" in stages:
        print("Performance…")
        res["perf"] = experiments.perf(system)
        figures.perf(res["perf"])

    write_json(results_path, res)
    (RESULTS / "RESULTS.md").write_text(summary_md(res), encoding="utf-8")
    # The paper (reports/, gitignored) includes figures from reports/figures
    dst = ROOT / "reports" / "figures"
    dst.mkdir(parents=True, exist_ok=True)
    for f in FIGURES.glob("*.pdf"):
        shutil.copy2(f, dst / f.name)
    print(f"Wrote {results_path}, RESULTS.md and {len(list(FIGURES.glob('*.pdf')))} figures.")


if __name__ == "__main__":
    main()
